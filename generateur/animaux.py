def _legs(xs, y0, y1, col, ph=0, w=14):
    out = ""
    for i, x in enumerate(xs):
        dx = ph * 12 * (1 if i % 2 == 0 else -1)
        out += LIMB(x, y0, x + dx, y1, col, w)
    return out

